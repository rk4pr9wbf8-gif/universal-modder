"""Grow Appalachia's focus tree with five more branches, from one table.

    python make_focus_tree.py

The first 47 focuses (the Veil, the Cryptid Corps, the Coven, Hollow Industry, the Midnight Pact, the
creeping fog) live hand-tuned in APL_focus.txt. This script appends a generated section to that file,
replacing the previous one, for:

- The Endless Hunt (cryptid warfare, under the Wild Hunt)
- The Council of Two Worlds (the Coven or the Mountain Assembly, under the Hollow Crown)
- The Hollow Treasury (the scrip economy, under the Black Furnace)
- The Black Library (occult science and the atom)
- Beyond the Fog (the Cold War: Moscow, Washington or neither; the bomb; the space race)

It also writes those branches' national spirits, Cold War events, localisation and icons.
"""

