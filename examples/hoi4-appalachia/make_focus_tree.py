F = []  # every new focus


def focus(fid, name, desc, x, y, reward, *, pre=(), mex=(), available="", cost=10, filt="POLITICAL", ai=1,
          icon=(("sigil", (18, 6, 59)),), ground="bruise"):
    F.append(dict(id=fid, name=name, desc=desc, x=x, y=y, reward=reward.strip("\n"), pre=pre, mex=mex,
                  available=available.strip("\n"), cost=cost, filt=filt, ai=ai, icon=icon, ground=ground))


# ---------------------------------------------------------------- reward snippets
def var(name, v):
    return f"add_to_variable = {{ {name} = {v} }}\n"


def scrip(n):
    return f"add_to_variable = {{ APL_treasury = {n} }}\ncustom_effect_tooltip = APL_ft_scrip_{n}_tt\n"


SCRIP_TT = set()


def scrip_tt(n):
    SCRIP_TT.add(n)
    return scrip(n)


def bop(v):
    return f"add_power_balance_value = {{\n\tid = APL_coven_balance\n\tvalue = {v}\n}}\n"


def build(kind, n):
    return ("random_owned_controlled_state = {\n\tlimit = { has_state_flag = APL_heartland }\n"
            f"\tadd_extra_state_shared_building_slots = {n}\n"
            f"\tadd_building_construction = {{\n\t\ttype = {kind}\n\t\tlevel = {n}\n\t\tinstant_build = yes\n\t}}\n}}\n")


def charms(n):
    return (f"add_equipment_to_stockpile = {{\n\ttype = APL_binding_charms_1\n\tamount = {n}\n\tproducer = APL\n}}\n")


def idea(key):
    return f"add_ideas = APL_{key}_spirit\n"


IDEAS = {}  # key: (name, desc, modifiers, (motif, ground))


def spirit(key, name, desc, mods, art):
    IDEAS[key] = (name, desc, mods, art)
    return idea(key)


