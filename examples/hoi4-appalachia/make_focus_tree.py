def tab(s, n):
    return "\n".join(("\t" * n + l) if l else "" for l in s.split("\n"))


def focus_text():
    out = [MARK]
    for d in F:
        out += ["\tfocus = {", f"\t\tid = {d['id']}", f"\t\ticon = GFX_goal_{d['id']}"]
        for g in d["pre"]:
            out.append("\t\tprerequisite = { " + " ".join(f"focus = {p}" for p in g) + " }")
        if d["mex"]:
            out.append("\t\tmutually_exclusive = { " + " ".join(f"focus = {p}" for p in d["mex"]) + " }")
        out += [f"\t\tx = {d['x']}", f"\t\ty = {d['y']}", f"\t\tcost = {d['cost']}"]
        if d["available"]:
            out += ["\t\tavailable = {", tab(d["available"], 3), "\t\t}"]
        out += [f"\t\tsearch_filters = {{ FOCUS_FILTER_{d['filt']} }}", "\t\tai_will_do = {", f"\t\t\tfactor = {d['ai']}",
                "\t\t}", "\t\tcompletion_reward = {", tab(d["reward"], 3), "\t\t}", "\t}", ""]
    return "\n".join(out)


