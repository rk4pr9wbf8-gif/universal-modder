def chars() -> str:
    out = ["# The leaders of 1949. Generated by make_cold_war.py from cold_war_1949.py.", "characters = {"]
    for tag, (party, pop, key, name, sub, cosmetic) in cw.COUNTRIES.items():
        out += [f"\tAPL_cw_{key} = {{", f"\t\tname = APL_cw_{key}", "\t\tcountry_leader = {",
                f"\t\t\tideology = {sub}", '\t\t\texpire = "1970.1.1.1"', "\t\t\tid = -1", "\t\t}", "\t}"]
    out.append("}")
    return "\n".join(out) + "\n"


def tag_scope(tag: str, body: str, indent="\t") -> str:
    """Scope into a country only if it exists. NOR is also the logical operator, so every country goes
    through every_country with a tag limit."""
    inner = "\n".join(indent + "\t" + l for l in body.strip().split("\n"))
    return f"{indent}every_country = {{\n{indent}\tlimit = {{ tag = {tag} }}\n{inner}\n{indent}}}\n"


def setup() -> str:
    s = ["# Generated by make_cold_war.py. Runs from on_startup when the game starts in 1949 or later.",
         "APL_cw_setup_1949 = {",
         '\tlog = "The Veiled Hollows 1949: start"',
         "\t# the wartime alliances are over",
         "\tevery_country = {\n\t\tlimit = { is_faction_leader = yes }\n\t\tdismantle_faction = yes\n\t}"]
    s.append('\tlog = "The Veiled Hollows 1949: leaders"')
    s.append("\t# 1949 heads of government")
    for tag, (party, pop, key, *_rest) in cw.COUNTRIES.items():
        s.append(tag_scope(tag, f"promote_character = APL_cw_{key}").rstrip("\n"))
    s.append('\tlog = "The Veiled Hollows 1949: capitals"')
    s.append("\t# new capitals and names")
    for tag, state in cw.CAPITALS.items():
        s.append(tag_scope(tag, f"if = {{\n\tlimit = {{ {state} = {{ is_owned_by = PREV }} }}\n\tset_capital = {{ state = {state} }}\n}}").rstrip("\n"))
    for tag, (party, pop, key, name, sub, cosmetic) in cw.COUNTRIES.items():
        if cosmetic:
            s.append(tag_scope(tag, f"set_cosmetic_tag = {cosmetic}").rstrip("\n"))
    s.append('\tlog = "The Veiled Hollows 1949: independence"')
    s.append("\t# independence")
    for overlord, subjects in cw.RELEASED.items():
        for sub in subjects:
            s.append(tag_scope(sub, f"if = {{\n\tlimit = {{ is_subject_of = {overlord} }}\n\t{overlord} = {{ end_puppet = PREV }}\n}}").rstrip("\n"))
    s.append('\tlog = "The Veiled Hollows 1949: puppets"')
    s.append("\t# occupation and client states")
    for overlord, subjects in cw.PUPPETS.items():
        for sub in subjects:
            s.append(tag_scope(sub, f"if = {{\n\tlimit = {{ NOT = {{ is_subject_of = {overlord} }} }}\n\t{overlord} = {{ puppet = PREV }}\n}}").rstrip("\n"))
    for leader, faction, members in (("USA", "APL_nato", cw.NATO), ("SOV", "APL_eastern_bloc", cw.EASTERN_BLOC)):
        s.append(f'\tlog = "The Veiled Hollows 1949: {faction}"')
        s.append(f"\t# {faction}")
        s.append(tag_scope(leader, f"create_faction = {faction}").rstrip("\n"))
        for m in members:
            s.append(tag_scope(m, f"if = {{\n\tlimit = {{ is_in_faction = no }}\n\t{leader} = {{ add_to_faction = PREV }}\n}}").rstrip("\n"))
    s.append('\tlog = "The Veiled Hollows 1949: china"')
    s.append("\t# the Chinese Civil War is still being fought")
    s.append("\tif = {\n\t\tlimit = {\n\t\t\tcountry_exists = PRC\n\t\t\tcountry_exists = CHI\n\t\t}\n"
             "\t\tPRC = {\n\t\t\tdeclare_war_on = {\n\t\t\t\ttarget = CHI\n\t\t\t\ttype = annex_everything\n\t\t\t}\n\t\t}\n\t}")
    s.append('\tlog = "The Veiled Hollows 1949: technology"')
    s.append('\tlog = "The Veiled Hollows 1949: armies"')
    s.append("\t# armies: a standard infantry template and divisions at the capital")
    template = ("division_template = {\n\tname = \"Infantry Division\"\n\tregiments = {\n"
                + "".join(f"\t\tinfantry = {{ x = {i // 3} y = {i % 3} }}\n" for i in range(6)) + "\t}\n}")
    unit = ('create_unit = {{\n\tdivision = "division_template = \\"Infantry Division\\" start_experience_factor = 0.3 '
            'start_equipment_factor = 0.8"\n\towner = THIS\n\tcount = {n}\n}}')
    for tag, n in cw.ARMY.items():
        if n:
            s.append(tag_scope(tag, template + "\n" + unit.format(n=n)).rstrip("\n"))
    others = " ".join(f"tag = {t}" for t in list(cw.ARMY) + ["APL"])
    s.append(f"\tevery_country = {{\n\t\tlimit = {{ NOT = {{ {others} }} }}\n"
             + "\n".join("\t\t" + l for l in (template + "\n" + unit.format(n=cw.ARMY_DEFAULT)).split("\n")) + "\n\t}")
    s.append("\t# 1949 technology (generated by build_mod.py from the game's own technologies)")
    s.append("\tAPL_cw_set_tech = yes")
    s.append('\tlog = "The Veiled Hollows 1949: done"')
    s.append("}")
    return "\n".join(s) + "\n"


