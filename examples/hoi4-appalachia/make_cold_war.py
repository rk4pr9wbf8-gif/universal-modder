def bookmark() -> str:
    out = ["bookmarks = {", "\tbookmark = {", '\t\tname = "APL_COLD_WAR_NAME"', '\t\tdesc = "APL_COLD_WAR_DESC"',
           "\t\tdate = 1949.5.23.12", '\t\tpicture = "GFX_select_date_APL_1949"', '\t\tdefault_country = "APL"',
           "\t\tdefault = yes", ""]
    for tag, ideo in BOOKMARK_MAJORS:
        out += [f'\t\t"{tag}" = {{', f'\t\t\thistory = "APL_CW_{tag}_DESC"', f"\t\t\tideology = {ideo}",
                "\t\t\tideas = { }", "\t\t\tfocuses = { }", "\t\t}"]
    out += ['\t\t"---" = {', '\t\t\thistory = "APL_CW_OTHER_DESC"', "\t\t}"]
    for tag, ideo in BOOKMARK_MINORS:
        out += [f'\t\t"{tag}" = {{', "\t\t\tminor = yes", f'\t\t\thistory = "APL_CW_{tag}_DESC"',
                f"\t\t\tideology = {ideo}", "\t\t\tideas = { }", "\t\t\tfocuses = { }", "\t\t}"]
    out += ["\t\teffect = {", "\t\t\trandomize_weather = 22345", "\t\t}", "\t}", "}"]
    return "\n".join(out) + "\n"


