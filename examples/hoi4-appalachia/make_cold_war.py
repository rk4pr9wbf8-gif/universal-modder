def flag_prk(size):
    w, h = size
    S = 8
    im = Image.new("RGBA", (w * S, h * S), (30, 60, 150, 255))
    d = ImageDraw.Draw(im)
    W, H = w * S, h * S
    d.rectangle([0, H * .18, W, H * .82], fill=(240, 240, 240, 255))
    d.rectangle([0, H * .22, W, H * .78], fill=(200, 20, 30, 255))
    cx, cy, r = W * .33, H * .5, H * .2
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(240, 240, 240, 255))
    import math
    pts = [(cx + math.cos(math.radians(-90 + i * 36)) * (r * .9 if i % 2 == 0 else r * .38),
            cy + math.sin(math.radians(-90 + i * 36)) * (r * .9 if i % 2 == 0 else r * .38)) for i in range(10)]
    d.polygon(pts, fill=(200, 20, 30, 255))
    return im.resize(size, Image.LANCZOS)


